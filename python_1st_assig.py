# Question 2 - String Slicing and Indexing
text = "Hello Zara, welcome to Python programming"
print("a.", text[0])                  # first character
print("b.", text[-1])                 # last character
print("c.", text[:5])                 # first 5 characters
print("d.", text[-11:])               # last 11 characters
print("e.", text[::-1])                   # reversed string
start = text.find("Python")               # position where "Python" begins
print("f.", text[start:start + 6])         # "Python" has 6 letters
print(" 'Python' starts at index", start)

